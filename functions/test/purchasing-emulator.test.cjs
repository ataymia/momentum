/* eslint-disable @typescript-eslint/no-require-imports */
"use strict";
const {test,after}=require("node:test");
const assert=require("node:assert/strict");
const {initializeApp,deleteApp}=require("firebase-admin/app");
const {getFirestore}=require("firebase-admin/firestore");
if(!process.env.FIRESTORE_EMULATOR_HOST)throw new Error("Purchasing test requires local emulator");
const app=initializeApp({projectId:"momentum-rules-test"});
const db=getFirestore(app);
const {commitPurchasingRequest}=require("../lib/purchasing-api.js");
const actor="qa-purchase-admin",ops="qa-purchase-ops",outside="qa-purchase-rep",warehouse="qa-purchase-warehouse";
const call=(uid,action,requestId)=>commitPurchasingRequest(uid,{mode:"write",action,requestId});
const key=(suffix)=>"qa-purchasing-key-"+suffix;
after(async()=>{await deleteApp(app);});
test("Connected purchasing uses authoritative roles, atomic receipts, replay and distinct approval",async()=>{
 await Promise.all([db.doc("userAccess/"+actor).set({role:"Administrator",accountState:"Active"}),db.doc("userAccess/"+ops).set({role:"Operations",accountState:"Active"}),db.doc("userAccess/"+outside).set({role:"Sales Representative",accountState:"Active"}),db.doc("userAccess/"+warehouse).set({role:"Warehouse",accountState:"Active"})]);
 await assert.rejects(()=>commitPurchasingRequest(outside,{mode:"read"}),e=>e.status===403);
 const action={kind:"vendor.add",name:"QA Supplier",contact:"QA only"};
 const first=await call(actor,action,key("vendor"));
 const vendor=first.state.vendors.find(v=>v.name==="QA Supplier");
 assert(vendor);
 const replay=await call(actor,action,key("vendor"));
 assert.equal(replay.state.vendors.filter(v=>v.name==="QA Supplier").length,1);
 await assert.rejects(()=>call(actor,{...action,name:"Changed"},key("vendor")),e=>e.status===409);
 await assert.rejects(()=>call(actor,{...action,role:"Administrator"},key("forged")),e=>e.status===400);
 const created=await call(ops,{kind:"po.create",vendorId:vendor.id,sku:"ge-original-250ml-24",cases:10,unitCostCents:1000,warehouse:"QA",expectedDate:"2026-12-01"},key("po"));
 const po=created.state.orders.find(p=>p.vendorId===vendor.id);
 assert(po);
 await call(ops,{kind:"po.submit",id:po.id},key("submit"));
 await assert.rejects(()=>call(ops,{kind:"po.approve",id:po.id},key("deny")),e=>e.status===409);
 const approved=await call(actor,{kind:"po.approve",id:po.id},key("approve"));
 assert.equal(approved.state.orders.find(p=>p.id===po.id).approvedBy,actor);
 const warehouseView=await commitPurchasingRequest(warehouse,{mode:"read"});
 assert.equal(warehouseView.state.orders.find(p=>p.id===po.id).unitCostCents,0);
 assert.equal(warehouseView.state.bills.length,0);
 await assert.rejects(()=>call(warehouse,{kind:"vendor.add",name:"Forbidden",contact:""},key("warehouse-denied")),e=>e.status===403);
 const receipt=await call(warehouse,{kind:"receipt.record",poId:po.id,cases:10,lotCode:"QA-LOT",bestBy:"2099-01-01",warehouse:"QA"},key("receipt"));
 assert.equal(receipt.state.receipts.find(r=>r.poId===po.id).inventoryPosted,false);
 const receiptId=receipt.state.receipts.find(r=>r.poId===po.id).id;
 await Promise.all([db.doc("domains/workspace/fields/inventory").set({items:[]}),db.doc("domains/commercial/fields/inventoryLots").set({items:[]}),db.doc("domains/inventoryLedger/fields/nodes").set({items:[{id:"node-warehouse-main",name:"QA",type:"Warehouse",active:true},{id:"node-external",name:"External",type:"External",active:true}]}),db.doc("domains/inventoryLedger/fields/movements").set({items:[]}),db.doc("domains/periodLocks/fields/locks").set({items:[]})]);
 const posting={kind:"receipt.post",id:receiptId,inspectionReference:"QA inspection 001"};
 await assert.rejects(()=>call(warehouse,posting,key("post-denied")),e=>e.status===403);
 const posted=await call(actor,posting,key("post"));
 assert.equal(posted.state.receipts.find(r=>r.id===receiptId).inventoryPosted,true);
 await call(actor,posting,key("post"));
 const movements=(await db.doc("domains/inventoryLedger/fields/movements").get()).data().items;
 assert.equal(movements.filter(m=>m.id==="purchase-receipt-"+receiptId).length,1);
 assert.equal(movements.find(m=>m.id==="purchase-receipt-"+receiptId).quantity,10);
 const billed=await call(ops,{kind:"bill.record",poId:po.id,invoiceNumber:"QA-BILL",cases:10,amountCents:10000},key("bill"));
 const bill=billed.state.bills.find(b=>b.poId===po.id);
 await call(actor,{kind:"bill.approve",id:bill.id},key("billapprove"));
 await db.doc("userAccess/"+ops).update({accountState:"Separated"});
 await assert.rejects(()=>commitPurchasingRequest(ops,{mode:"read"}),e=>e.status===403);
 assert.equal((await db.doc("purchasingRegisters/current").get()).data().state.bills.find(b=>b.id===bill.id).amountCents,10000);
});
